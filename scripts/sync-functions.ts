// Copies the pure-TS modules the Edge Functions share with the app into supabase/functions/_shared/core/,
// adding the ".ts" extension Deno needs to relative imports. Run after changing any of these files:
//
//   npm run sync-functions
//
// A Jest test (src/core/syncFunctions.test.ts) fails if the copies are out of date.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const SHARED_FILES = ['types.ts', 'vehicle/types.ts', 'vehicle/normalize.ts', 'vehicle/nhtsa.ts', 'photoCheck/types.ts'] as const;

const ROOT = join(__dirname, '..');
export const SRC = join(ROOT, 'src/core');
export const DEST = join(ROOT, 'supabase/functions/_shared/core');

const HEADER = '// GENERATED by scripts/sync-functions.ts from src/core/. Do not edit here; edit the app file and re-run.\n';

/** Adds ".ts" to relative imports that have no extension. */
export function denoify(source: string): string {
  return HEADER + source.replace(/(from\s+['"])(\.{1,2}\/[^'"]+?)(?<!\.ts|\.json)(['"])/g, '$1$2.ts$3');
}

export function complaintGroupsJson(): string {
  const checklist = JSON.parse(readFileSync(join(ROOT, 'data/inspection_checklist.json'), 'utf8'));
  return JSON.stringify(checklist._meta.complaint_keyword_groups, null, 2) + '\n';
}

function main() {
  for (const f of SHARED_FILES) {
    const out = join(DEST, f);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, denoify(readFileSync(join(SRC, f), 'utf8')));
  }
  writeFileSync(join(DEST, 'complaintGroups.json'), complaintGroupsJson());
  console.log(`Synced ${SHARED_FILES.length} files + complaintGroups.json to ${DEST}`);
}

if (require.main === module) main();
